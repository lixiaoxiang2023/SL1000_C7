/*****************************************************************************************
函数名：uint32_t WriteFlash( uint16_t *pwIndat,uint32_t dwLenth )
参数描述：
        uint16_t *pwIndat：需要写入Flash的字的首地址
        uint32_t dwLenth：需要写入的数据长度
返回值描述：
        写入Flash失败时将会返回1
        正确是返回0
说明：
        此函数将会从flash的0x08000800地址开始写数据，写入的追打长度为8k
特殊算法：无
注意事项：无
*****************************************************************************************/
uint32_t WriteFlash( uint16_t *pwIndat,uint32_t dwLenth )
{
        FLASH_Unlock();
        for(uint32_t i = 0; i < 13; i++)
        {
            //FLASH_ErasePage(0x08000800 + (i * 0x800));
        }

        for(uint32_t i = 0 ; i < dwLenth ; i++,pwIndat ++)
        {
                FLASH_ProgramHalfWord(0x08000800 + (2 * i),(*pwIndat));

                if(*(uint16_t *)(0x08000800 + (2 * i)) != (*pwIndat))
                {
                        return 1;
                }
        }

        FLASH_Lock();

        return 0;
}