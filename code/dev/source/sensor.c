static void Init(void)
{
    DevIo->RemapConfig(GPIO_Remap_SWJ_JTAGDisable,ENABLE);
    DevIo->Config(PD, 4, 1, Mode_IN_FLOATING);//401光耦  滴镜油位有无试纸卡 J15
    DevIo->Config(PD, 2, 1, Mode_IN_FLOATING);//401光耦 检测有无载玻片//J25
    DevIo->Config(PD, 6, 1, Mode_IPD);//行程开关，用于检测试纸盒有无，配置下拉输入，高电平有效 载玻片盒子 J18
    DevIo->Config(PD, 3, 1, Mode_IN_FLOATING);//染剂位有无试纸卡 J21
    //DevIo->Config(PB, 1, 1, Mode_IN_FLOATING);//镜油检测光耦
    DevIo->Config(PD, 8, 1, Mode_IN_FLOATING);//镜油检测光耦5
    DevIo->Config(PD, 5, 1, Mode_IN_FLOATING);//镜油检测光耦5
}

