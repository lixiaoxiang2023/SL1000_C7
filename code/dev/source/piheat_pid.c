float PidLocFan(stPidTdf *pstPid)
{
  if(!pstPid) return 0;
  if(pstPid->Temset == 0) return 0;
  pstPid->dev = (pstPid->Temset - pstPid->Temin)/10;//比例

  pstPid->dev_sum += pstPid->dev;    //累计误差

  pstPid->fout = pstPid->Kp * pstPid->dev + (pstPid->Ki * pstPid->dev_sum) + pstPid->Kd * (pstPid->dev_last - pstPid->dev)+5;//8 pstPid->dev - pstPid->dev_last 4

  pstPid->dev_last = pstPid->dev;
  if(isnan(pstPid->dev_sum)) pstPid->dev_sum = 0;
  if(pstPid->fout > 300) pstPid->dev_sum = 300;
  
  return pstPid->fout;
}