#include "devplat.h"

#if(CONFIG_MCP3202)
/*******************************************************************************
常量定义
*******************************************************************************/
#define MCP32XX_CH1         0xa0
#define MCP32XX_CH2         0xe0

/*******************************************************************************
全局变量定义
*******************************************************************************/

/*******************************************************************************
数据结构与数据类型定义
*******************************************************************************/

/*******************************************************************************
内部全局变量申明
*******************************************************************************/
static struct {
    unsigned char bySpiNo;
    unsigned int  *pdwCs;
}s_stCtr;

/*******************************************************************************
内部函数申明
*******************************************************************************/

/*******************************************************************************
函数功能：
*   @ 读取adc结果
参数描述：
*   @ uint32_t dwChn：0：通道1，1：通道2
返回值描述：
*   @ 采样结果
说明：
*   @ 无
*******************************************************************************/
static uint16_t Read(uint32_t dwChn)
{
    uint8_t byaGet[3];

    byaGet[0] = 0x01;
    byaGet[1] = (dwChn == 0)?MCP32XX_CH1 : MCP32XX_CH2;
    byaGet[2] = 0;

    DevSpi->Trs(s_stCtr.bySpiNo, byaGet, byaGet, 3, s_stCtr.pdwCs);

   return ((unsigned short int)((byaGet[1] & 0x0f) << 8) + byaGet[2]);
}

static const DevMcp3202Tdf s_Dev = {
    Read,
};

/*******************************************************************************
函数功能：
*   @ 初始化Mcp3202
参数描述：
*   @ 无
返回值描述：
*   @ 3626的操作方法集合
说明：
*******************************************************************************/
const DevMcp3202Tdf *Mcp3202Init(Mcp3202InitTdf *pstInit)
{
    s_stCtr.bySpiNo = pstInit->bySpiNo;

    s_stCtr.pdwCs = pstInit->pwdSpiNcs;
    *s_stCtr.pdwCs = 1;
    DevSpi->Config(s_stCtr.bySpiNo, pstInit->dwSpiBaud);   // 32

    return &s_Dev;
}

#endif